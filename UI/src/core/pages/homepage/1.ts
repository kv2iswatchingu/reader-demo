以太网介质用于两种基本拓扑结构：“总线”和“星形”。拓扑定义节点（任何设备，如计算机、打印机或集线器）如何连接到网络。总线拓扑由通过一根长电缆连接的节点组成。每个节点“分接”到总线中，直接与总线上的所有其他节点通信

这种拓扑的主要优点是通过添加额外的“抽头”轻松扩展，并且没有集线器。主要缺点是任何电缆断裂都会导致所有电缆节点失去与网络的连接

星形拓扑将网络上的两个节点恰好连接在一起。集线器用于许多连接汇集在一起的收集点。主要优点是任何单个中断都只禁用一个主机。主要缺点是集线器的成本增加

